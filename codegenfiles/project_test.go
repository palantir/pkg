// Output produced by one source must not be treated as stale because another source did not produce it.
// This is why everything written into a managed directory goes through a single Project.
func TestPlan_DoesNotRemoveOutputFromAnotherSource(t *testing.T) {
	projectDir := t.TempDir()
	genDir := filepath.Join(projectDir, "gen")
	mkdirAll(t, genDir)
	writeFile(t, filepath.Join(genDir, "a.go"), string(keptContent()))
	writeFile(t, filepath.Join(genDir, "b.go"), string(keptContent()))

	out := codegenfiles.NewOutput()
	out.Add(filepath.Join("gen", "a.go"), keptContent()) // source A
	out.AddAll(map[string][]byte{                        // source B
		filepath.Join("gen", "b.go"): keptContent(),
	})

	changes, err := newProject(projectDir).Plan(out)
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if !changes.Empty() {
		t.Errorf("expected no changes, got:\n%s", changes)
	}
}

