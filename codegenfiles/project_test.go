const generatedHeader = "// Code generated by test. DO NOT EDIT.\n\npackage gen\n"

func keptContent() []byte { return []byte(generatedHeader + "// kept\n") }

// newProject returns a Project that owns every .go file under dir and deletes stale generated ones.
func newProject(dir string) *codegenfiles.Project {
	return &codegenfiles.Project{
		Dir:             dir,
		FileMatcher:     matcher.Name(`.+\.go`),
		ContentsMatcher: codegenfiles.GeneratedCodeMatcher(),
		DeleteStale:     true,
	}
}

// outputWith returns an Output containing gen/kept.go with the standard content.
func outputWith(paths ...string) *codegenfiles.Output {
	out := codegenfiles.NewOutput()
	for _, p := range paths {
		out.Add(p, keptContent())
	}
	return out
}

func TestPlan_ReportsMissingOutOfDateAndStaleFiles(t *testing.T) {
	projectDir := t.TempDir()
	genDir := filepath.Join(projectDir, "gen")
	mkdirAll(t, genDir)
	writeFile(t, filepath.Join(genDir, "outdated.go"), generatedHeader+"// old\n")
	writeFile(t, filepath.Join(genDir, "stale.go"), generatedHeader+"// stale\n")
	writeFile(t, filepath.Join(genDir, "hand.go"), "package gen\n")

	out := outputWith(filepath.Join("gen", "outdated.go"), filepath.Join("gen", "created.go"))
	changes, err := newProject(projectDir).Plan(out)
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}

	assertWrites(t, changes, map[string]bool{
		filepath.Join("gen", "created.go"):  true,  // does not exist yet
		filepath.Join("gen", "outdated.go"): false, // exists with different content
	})
	assertRemovals(t, changes, filepath.Join("gen", "stale.go")) // hand.go has no marker, so is preserved

	// Plan must not have touched the filesystem
	assertNotExists(t, filepath.Join(genDir, "created.go"))
	assertExists(t, filepath.Join(genDir, "stale.go"))
	assertContent(t, filepath.Join(genDir, "outdated.go"), generatedHeader+"// old\n")
}

func TestPlan_UpToDateDirectoryIsEmpty(t *testing.T) {
	projectDir := t.TempDir()
	genDir := filepath.Join(projectDir, "gen")
	mkdirAll(t, genDir)
	writeFile(t, filepath.Join(genDir, "kept.go"), string(keptContent()))

	changes, err := newProject(projectDir).Plan(outputWith(filepath.Join("gen", "kept.go")))
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if !changes.Empty() {
		t.Errorf("expected no changes, got:\n%s", changes)
	}
	if err := changes.Err(); err != nil {
		t.Errorf("expected Err to be nil for an up-to-date project, got: %v", err)
	}
}

func TestApply_WritesDeletesAndPreserves(t *testing.T) {
	projectDir := t.TempDir()
	genDir := filepath.Join(projectDir, "gen")
	mkdirAll(t, genDir)
	writeFile(t, filepath.Join(genDir, "stale.go"), generatedHeader+"// stale\n")
	writeFile(t, filepath.Join(genDir, "hand.go"), "package gen\n")

	p := newProject(projectDir)
	changes, err := p.Plan(outputWith(filepath.Join("gen", "kept.go")))
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if err := changes.Apply(); err != nil {
		t.Fatalf("Apply: %v", err)
	}

	assertContent(t, filepath.Join(genDir, "kept.go"), string(keptContent()))
	assertExists(t, filepath.Join(genDir, "hand.go"))
	assertNotExists(t, filepath.Join(genDir, "stale.go"))

	// applying twice must be a no-op: re-planning the same output finds nothing to do
	changes, err = p.Plan(outputWith(filepath.Join("gen", "kept.go")))
	if err != nil {
		t.Fatalf("second Plan: %v", err)
	}
	if !changes.Empty() {
		t.Errorf("expected the second plan to be empty, got:\n%s", changes)
	}
}

// An unchanged file must not be rewritten. Rewriting churns modification times, which editors, file
// watchers and mtime-based tools react to. It does not affect the Go build cache, which keys on content.
func TestApply_LeavesUnchangedFilesAlone(t *testing.T) {
	projectDir := t.TempDir()
	genDir := filepath.Join(projectDir, "gen")
	mkdirAll(t, genDir)
	keptPath := filepath.Join(genDir, "kept.go")
	writeFile(t, keptPath, string(keptContent()))

	before, err := os.Stat(keptPath)
	if err != nil {
		t.Fatal(err)
	}
	// ensure a rewrite would be observable in the modification time
	stale := before.ModTime().Add(-time.Hour)
	if err := os.Chtimes(keptPath, stale, stale); err != nil {
		t.Fatal(err)
	}

	changes, err := newProject(projectDir).Plan(outputWith(filepath.Join("gen", "kept.go")))
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if err := changes.Apply(); err != nil {
		t.Fatalf("Apply: %v", err)
	}

	after, err := os.Stat(keptPath)
	if err != nil {
		t.Fatal(err)
	}
	if !after.ModTime().Equal(stale) {
		t.Errorf("unchanged file was rewritten: mtime moved from %v to %v", stale, after.ModTime())
	}
}

// Removing the last file in a directory removes the directory too, all the way up to the project
// directory. Cleanup deliberately does not consult FileMatcher: it climbs only through directories that
// the removal itself emptied, and a matcher that selects files (matcher.Name(`.+\.go`) matches no
// directory at all) cannot describe which directories a project owns.
func TestApply_RemovesEveryDirectoryEmptiedByARemoval(t *testing.T) {
	projectDir := t.TempDir()
	nested := filepath.Join(projectDir, "gen", "api", "v1")
	mkdirAll(t, nested)
	writeFile(t, filepath.Join(nested, "stale.go"), generatedHeader+"// stale\n")

	changes, err := newProject(projectDir).Plan(codegenfiles.NewOutput())
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if err := changes.Apply(); err != nil {
		t.Fatalf("Apply: %v", err)
	}
	assertNotExists(t, nested)
	assertNotExists(t, filepath.Join(projectDir, "gen", "api"))
	assertNotExists(t, filepath.Join(projectDir, "gen"))
	assertExists(t, projectDir) // the climb stops at the project directory
}

