// metric-schema merges several schema files into one output directory, where two schemas producing the
// same path would otherwise silently overwrite each other.
func TestPlan_DuplicatePathIsRejected(t *testing.T) {
	out := codegenfiles.NewOutput()
	out.Add(filepath.Join("gen", "dup.go"), keptContent())
	out.Add(filepath.Join("gen", "dup.go"), keptContent())

	_, err := newProject(t.TempDir()).Plan(out)
	if err == nil {
		t.Fatal("expected an error when the same path is produced twice, got nil")
	}
	if !strings.Contains(err.Error(), "more than once") {
		t.Errorf("error should describe the duplicate, got: %v", err)
	}
}

// The same path reached by different spellings is still the same path.
func TestPlan_DuplicateViaAbsoluteAndRelativePathIsRejected(t *testing.T) {
	projectDir := t.TempDir()
	out := codegenfiles.NewOutput()
	out.Add(filepath.Join("gen", "dup.go"), keptContent())
	out.Add(filepath.Join(projectDir, "gen", "dup.go"), keptContent())

	if _, err := newProject(projectDir).Plan(out); err == nil {
		t.Fatal("expected an error when a path is produced both relatively and absolutely, got nil")
	}
}

func TestPlan_EscapingPathIsRejected(t *testing.T) {
	for _, path := range []string{
		filepath.Join("..", "evil.go"),
		filepath.Join("gen", "..", "..", "evil.go"),
	} {
		out := codegenfiles.NewOutput()
		out.Add(path, keptContent())
		if _, err := newProject(t.TempDir()).Plan(out); err == nil {
			t.Errorf("expected an error for path %q escaping the project directory, got nil", path)
		}
	}
}

// A directory standing where a generated file must go is cleared by the removals Apply performs first,
// rather than failing the write as it did when writes came first.
func TestApply_ReplacesDirectoryLeftByAPreviousRun(t *testing.T) {
	projectDir := t.TempDir()
	// a previous run produced gen/kept.go as a directory containing generated files
	obsolete := filepath.Join(projectDir, "gen", "kept.go")
	mkdirAll(t, obsolete)
	writeFile(t, filepath.Join(obsolete, "old.go"), generatedHeader+"// old\n")

	p := newProject(projectDir)
	changes, err := p.Plan(outputWith(filepath.Join("gen", "kept.go")))
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if err := changes.Apply(); err != nil {
		t.Fatalf("Apply: %v", err)
	}
	assertContent(t, filepath.Join(projectDir, "gen", "kept.go"), string(keptContent()))
}

func TestPlan_DeleteStaleDisabledIgnoresUngeneratedFiles(t *testing.T) {
	projectDir := t.TempDir()
	genDir := filepath.Join(projectDir, "gen")
	mkdirAll(t, genDir)
	writeFile(t, filepath.Join(genDir, "stale.go"), generatedHeader+"// stale\n")

	p := newProject(projectDir)
	p.DeleteStale = false

	changes, err := p.Plan(outputWith(filepath.Join("gen", "kept.go")))
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if len(changes.Removals()) != 0 {
		t.Errorf("expected no removals with DeleteStale disabled, got %v", changes.Removals())
	}
	if err := changes.Apply(); err != nil {
		t.Fatalf("Apply: %v", err)
	}
	assertExists(t, filepath.Join(genDir, "stale.go"))
}

func TestChanges_StringListsEveryChangeSortedByPath(t *testing.T) {
	projectDir := t.TempDir()
	genDir := filepath.Join(projectDir, "gen")
	mkdirAll(t, genDir)
	writeFile(t, filepath.Join(genDir, "b.go"), generatedHeader+"// old\n")
	writeFile(t, filepath.Join(genDir, "c.go"), generatedHeader+"// stale\n")

	out := outputWith(filepath.Join("gen", "a.go"), filepath.Join("gen", "b.go"))
	changes, err := newProject(projectDir).Plan(out)
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}

	want := strings.Join([]string{
		filepath.Join("gen", "a.go") + ": missing",
		filepath.Join("gen", "b.go") + ": out of date",
		filepath.Join("gen", "c.go") + ": no longer generated",
	}, "\n")
	if got := changes.String(); got != want {
		t.Errorf("String() =\n%s\nwant:\n%s", got, want)
	}
}
